package com.bentza.sna.gui;

import com.bentza.sna.net.Network;
import com.bentza.sna.stats.HypothesisTestResult;
import com.bentza.sna.stats.NetworkHypothesisTester;
import com.bentza.sna.stats.NetworkMetric;
import com.bentza.sna.stats.NullModel;
import java.awt.BorderLayout;
import java.awt.Color;
import java.awt.Dimension;
import java.awt.FlowLayout;
import java.awt.Font;
import java.awt.Frame;
import java.awt.GridBagConstraints;
import java.awt.GridBagLayout;
import java.awt.Insets;
import java.util.function.Consumer;
import javax.swing.BorderFactory;
import javax.swing.JButton;
import javax.swing.JComboBox;
import javax.swing.JDialog;
import javax.swing.JLabel;
import javax.swing.JOptionPane;
import javax.swing.JPanel;
import javax.swing.JProgressBar;
import javax.swing.JScrollPane;
import javax.swing.JTextArea;
import javax.swing.SwingWorker;

/**
 * Interactive dialog for running Monte Carlo statistical hypothesis tests
 * comparing observed social network metrics against null models.
 */
public class HypothesisTestingDialog extends JDialog
    {
    private final Network network;
    private final Consumer<String> outputAppender;

    private JComboBox<NetworkMetric> metricCombo;
    private JComboBox<NullModel> modelCombo;
    private JComboBox<Integer> repCombo;
    private JLabel metricDescLabel;
    private JLabel modelDescLabel;

    private JButton runButton;
    private JButton closeButton;
    private JProgressBar progressBar;
    private JTextArea resultArea;

    public HypothesisTestingDialog(Frame owner, Network network, Consumer<String> outputAppender)
        {
        super(owner, "Statistical Hypothesis Testing (Null Models)", true);
        this.network = network;
        this.outputAppender = outputAppender;

        initComponents();
        pack();
        setMinimumSize(new Dimension(620, 520));
        setLocationRelativeTo(owner);
        }

    private void initComponents()
        {
        setLayout(new BorderLayout(10, 10));

        // Top Header
        JPanel headerPanel = new JPanel(new BorderLayout(5, 5));
        headerPanel.setBorder(BorderFactory.createEmptyBorder(12, 14, 6, 14));
        JLabel titleLabel = new JLabel("Monte Carlo Null Model Testing");
        titleLabel.setFont(titleLabel.getFont().deriveFont(Font.BOLD, 15f));
        titleLabel.setForeground(new Color(0, 64, 128));

        String netInfo = (network != null)
                ? String.format("Network: %s (%d nodes)",
                        network.getName() != null ? network.getName() : "Current", network.getSize())
                : "No active network";
        JLabel subLabel = new JLabel("<html>Compare observed network metrics against chance distributions generated by constrained randomized models.<br><b>"
                + netInfo + "</b></html>");
        subLabel.setFont(subLabel.getFont().deriveFont(12f));

        headerPanel.add(titleLabel, BorderLayout.NORTH);
        headerPanel.add(subLabel, BorderLayout.CENTER);
        add(headerPanel, BorderLayout.NORTH);

        // Center Panel: Controls & Results
        JPanel centerPanel = new JPanel(new BorderLayout(8, 8));
        centerPanel.setBorder(BorderFactory.createEmptyBorder(0, 14, 0, 14));

        // Options form
        JPanel formPanel = new JPanel(new GridBagLayout());
        formPanel.setBorder(BorderFactory.createTitledBorder("Test Parameters"));
        GridBagConstraints gbc = new GridBagConstraints();
        gbc.insets = new Insets(5, 6, 5, 6);
        gbc.anchor = GridBagConstraints.WEST;
        gbc.fill = GridBagConstraints.HORIZONTAL;

        // Metric
        gbc.gridx = 0; gbc.gridy = 0; gbc.weightx = 0.0;
        formPanel.add(new JLabel("Test Metric:"), gbc);
        gbc.gridx = 1; gbc.weightx = 1.0;
        metricCombo = new JComboBox<>(NetworkMetric.values());
        metricCombo.setSelectedItem(NetworkMetric.TRANSITIVITY);
        metricCombo.setToolTipText("<html><b>Test Metric:</b> Select the network statistic to evaluate against synthetic null distributions.</html>");
        formPanel.add(metricCombo, gbc);

        gbc.gridx = 1; gbc.gridy = 1;
        metricDescLabel = new JLabel("<html><small style='color:#555;'>" + NetworkMetric.TRANSITIVITY.getDescription() + "</small></html>");
        formPanel.add(metricDescLabel, gbc);

        // Null Model
        gbc.gridx = 0; gbc.gridy = 2; gbc.weightx = 0.0;
        formPanel.add(new JLabel("Null Model:"), gbc);
        gbc.gridx = 1; gbc.weightx = 1.0;
        modelCombo = new JComboBox<>(NullModel.values());
        modelCombo.setSelectedItem(NullModel.DEGREE_PRESERVING);
        modelCombo.setToolTipText("<html><b>Null Model:</b> The random graph model used to generate baseline synthetic networks.</html>");
        formPanel.add(modelCombo, gbc);

        gbc.gridx = 1; gbc.gridy = 3;
        modelDescLabel = new JLabel("<html><small style='color:#555;'>" + NullModel.DEGREE_PRESERVING.getDescription() + "</small></html>");
        formPanel.add(modelDescLabel, gbc);

        // Replications
        gbc.gridx = 0; gbc.gridy = 4; gbc.weightx = 0.0;
        formPanel.add(new JLabel("Replications:"), gbc);
        gbc.gridx = 1; gbc.weightx = 1.0;
        repCombo = new JComboBox<>(new Integer[] { 100, 500, 1000, 5000 });
        repCombo.setSelectedItem(1000);
        repCombo.setToolTipText("<html><b>Monte Carlo Replications (R):</b> Recommended: 1,000 for standard research empirical p-value resolution (0.001).</html>");
        formPanel.add(repCombo, gbc);

        metricCombo.addActionListener(e ->
            {
            NetworkMetric m = (NetworkMetric) metricCombo.getSelectedItem();
            if (m != null)
                metricDescLabel.setText("<html><small style='color:#555;'>" + m.getDescription() + "</small></html>");
            });

        modelCombo.addActionListener(e ->
            {
            NullModel m = (NullModel) modelCombo.getSelectedItem();
            if (m != null)
                modelDescLabel.setText("<html><small style='color:#555;'>" + m.getDescription() + "</small></html>");
            });

        centerPanel.add(formPanel, BorderLayout.NORTH);

        // Results preview area
        resultArea = new JTextArea();
        resultArea.setFont(new Font(Font.MONOSPACED, Font.PLAIN, 12));
        resultArea.setEditable(false);
        resultArea.setText("Select parameters and click 'Run Hypothesis Test' to compute Monte Carlo null distributions.\nResults will also be automatically appended to the Output tab in the main window.");
        JScrollPane scrollPane = new JScrollPane(resultArea);
        scrollPane.setBorder(BorderFactory.createTitledBorder("Results & Null Distribution"));
        centerPanel.add(scrollPane, BorderLayout.CENTER);

        add(centerPanel, BorderLayout.CENTER);

        // Bottom Panel: Progress and Buttons
        JPanel bottomPanel = new JPanel(new BorderLayout(5, 5));
        bottomPanel.setBorder(BorderFactory.createEmptyBorder(6, 14, 12, 14));

        progressBar = new JProgressBar();
        progressBar.setVisible(false);
        progressBar.setStringPainted(true);
        progressBar.setString("Simulating random graph ensemble...");
        bottomPanel.add(progressBar, BorderLayout.NORTH);

        JPanel buttonPanel = new JPanel(new FlowLayout(FlowLayout.RIGHT, 8, 4));
        runButton = new JButton("Run Hypothesis Test");
        runButton.setFont(runButton.getFont().deriveFont(Font.BOLD));
        closeButton = new JButton("Close");

        runButton.addActionListener(e -> runHypothesisTest());
        closeButton.addActionListener(e -> setVisible(false));

        buttonPanel.add(runButton);
        buttonPanel.add(closeButton);
        bottomPanel.add(buttonPanel, BorderLayout.SOUTH);

        add(bottomPanel, BorderLayout.SOUTH);
        }

    private void runHypothesisTest()
        {
        if (network == null || network.getSize() < 3)
            {
            JOptionPane.showMessageDialog(this,
                    "A network with at least 3 nodes is required for null model testing.",
                    "Network Too Small", JOptionPane.WARNING_MESSAGE);
            return;
            }

        NetworkMetric metric = (NetworkMetric) metricCombo.getSelectedItem();
        NullModel model = (NullModel) modelCombo.getSelectedItem();
        int reps = (Integer) repCombo.getSelectedItem();

        runButton.setEnabled(false);
        closeButton.setEnabled(false);
        progressBar.setIndeterminate(true);
        progressBar.setVisible(true);
        resultArea.setText("Simulating " + reps + " randomized benchmark networks under " + model.getDisplayName() + "...\nPlease wait.");

        SwingWorker<HypothesisTestResult, Void> worker = new SwingWorker<HypothesisTestResult, Void>()
            {
            @Override
            protected HypothesisTestResult doInBackground() throws Exception
                {
                return NetworkHypothesisTester.runTest(network, metric, model, reps);
                }

            @Override
            protected void done()
                {
                progressBar.setVisible(false);
                runButton.setEnabled(true);
                closeButton.setEnabled(true);
                try
                    {
                    HypothesisTestResult res = get();
                    resultArea.setText(res.toTextReport());
                    resultArea.setCaretPosition(0);

                    // Append rich HTML report to main window Output tab
                    if (outputAppender != null)
                        {
                        outputAppender.accept(res.toHtmlReport());
                        }
                    }
                catch (Exception ex)
                    {
                    resultArea.setText("Error during simulation: " + ex.getMessage());
                    JOptionPane.showMessageDialog(HypothesisTestingDialog.this,
                            "An error occurred while evaluating the null model: " + ex.getMessage(),
                            "Simulation Error", JOptionPane.ERROR_MESSAGE);
                    }
                }
            };

        worker.execute();
        }
    }
